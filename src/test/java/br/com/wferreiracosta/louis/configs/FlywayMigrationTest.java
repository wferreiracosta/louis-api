package br.com.wferreiracosta.louis.configs;

import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.FlywayException;
import org.flywaydb.core.api.MigrationInfo;
import org.flywaydb.core.api.MigrationState;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.orm.jpa.LocalContainerEntityManagerFactoryBean;
import org.springframework.orm.jpa.vendor.HibernateJpaVendorAdapter;

import javax.sql.DataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.ResultSet;
import java.sql.Statement;
import java.util.Arrays;
import java.util.Properties;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

class FlywayMigrationTest {

    private DataSource createPostgresModeH2DataSource() {
        String dbName = "flyway_test_" + UUID.randomUUID().toString().replace("-", "");
        JdbcDataSource ds = new JdbcDataSource();
        ds.setURL("jdbc:h2:mem:" + dbName + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        ds.setUser("sa");
        ds.setPassword("");
        return ds;
    }

    private LocalContainerEntityManagerFactoryBean createValidatingEntityManagerFactory(DataSource ds) {
        LocalContainerEntityManagerFactoryBean em = new LocalContainerEntityManagerFactoryBean();
        em.setDataSource(ds);
        em.setPackagesToScan("br.com.wferreiracosta.louis.models.entities");

        HibernateJpaVendorAdapter vendorAdapter = new HibernateJpaVendorAdapter();
        vendorAdapter.setShowSql(false);
        vendorAdapter.setGenerateDdl(false);
        em.setJpaVendorAdapter(vendorAdapter);

        Properties properties = new Properties();
        properties.setProperty("hibernate.hbm2ddl.auto", "validate");
        properties.setProperty("hibernate.dialect", "org.hibernate.dialect.H2Dialect");
        properties.setProperty("hibernate.physical_naming_strategy",
                "org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy");
        properties.setProperty("hibernate.implicit_naming_strategy",
                "org.springframework.boot.orm.jpa.hibernate.SpringImplicitNamingStrategy");
        em.setJpaProperties(properties);

        return em;
    }

    @Test
    @DisplayName("Applies V1, V2, V3 in order, records history, and passes Hibernate ddl-auto=validate")
    void appliesInitialMigrationsAndPassesHibernateValidate() throws Exception {
        DataSource ds = createPostgresModeH2DataSource();

        Flyway flyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("3")
                .load();

        var result = flyway.migrate();
        assertThat(result.migrationsExecuted).isEqualTo(3);

        MigrationInfo[] applied = flyway.info().applied();
        assertThat(Arrays.stream(applied).map(info -> info.getVersion().getVersion()))
                .containsExactly("1", "2", "3");
        assertThat(Arrays.stream(applied).map(MigrationInfo::getScript))
                .containsExactly(
                        "V1__create_users_table.sql",
                        "V2__create_wallets_table.sql",
                        "V3__create_transactions_table.sql"
                );

        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(
                     "SELECT version, success FROM flyway_schema_history WHERE version IS NOT NULL ORDER BY installed_rank")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("version")).isEqualTo("1");
            assertThat(rs.getBoolean("success")).isTrue();
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("version")).isEqualTo("2");
            assertThat(rs.getBoolean("success")).isTrue();
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("version")).isEqualTo("3");
            assertThat(rs.getBoolean("success")).isTrue();
            assertThat(rs.next()).isFalse();
        }

        // Validate schema generated by V1..V3 against JPA entities
        LocalContainerEntityManagerFactoryBean em = createValidatingEntityManagerFactory(ds);
        em.afterPropertiesSet();

        // Insert a row and re-run migrate() to verify idempotency and data preservation
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("INSERT INTO users (name, surname, document, email, password, password_encoding, type) " +
                    "VALUES ('Ana', 'Lima', '12345678901', 'ana@test.com', '$2a$10$hash', 'BCRYPT', 'COMMON')");
        }

        var rerun = flyway.migrate();
        assertThat(rerun.migrationsExecuted).isZero();

        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT count(*) FROM users WHERE email = 'ana@test.com'")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getInt(1)).isEqualTo(1);
        }

        em.destroy();
    }

    @Test
    @DisplayName("Applies incremental V4 migration in isolated fixture without recreating existing tables")
    void appliesIncrementalV4MigrationWithoutRecreatingTables(@TempDir Path tempDir) throws Exception {
        DataSource ds = createPostgresModeH2DataSource();

        // Step 1: Apply V1..V3
        Flyway initialFlyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration")
                .load();
        assertThat(initialFlyway.migrate().migrationsExecuted).isEqualTo(3);

        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.executeUpdate("INSERT INTO users (name, surname, document, email, password, type) " +
                    "VALUES ('Bruno', 'Costa', '99988877766', 'bruno@test.com', 'hash', 'COMMON')");
        }

        // Step 2: Add isolated V4 script in tempDir and run Flyway across both locations
        Files.writeString(tempDir.resolve("V4__add_audit_note_column.sql"),
                "ALTER TABLE users ADD COLUMN audit_note VARCHAR(100);");

        Flyway incrementalFlyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration", "filesystem:" + tempDir.toAbsolutePath())
                .load();
        var result = incrementalFlyway.migrate();
        assertThat(result.migrationsExecuted).isEqualTo(1);

        assertThat(Arrays.stream(incrementalFlyway.info().applied()).map(info -> info.getVersion().getVersion()))
                .containsExactly("1", "2", "3", "4");

        // Existing data must remain intact and new column must exist
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT name, audit_note FROM users WHERE email = 'bruno@test.com'")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getString("name")).isEqualTo("Bruno");
            assertThat(rs.getString("audit_note")).isNull();
        }
    }

    @Test
    @DisplayName("Baselines pre-existing non-empty schema at version 3 without re-executing V1..V3")
    void baselinesPreExistingSchemaAtVersion3(@TempDir Path tempDir) throws Exception {
        DataSource ds = createPostgresModeH2DataSource();

        // Simulate pre-existing schema provisioned before Flyway adoption
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("""
                    CREATE TABLE users (
                        id BIGSERIAL PRIMARY KEY,
                        name VARCHAR(255) NOT NULL,
                        surname VARCHAR(255) NOT NULL,
                        document VARCHAR(255) NOT NULL UNIQUE,
                        email VARCHAR(255) NOT NULL UNIQUE,
                        password VARCHAR(255) NOT NULL,
                        password_encoding VARCHAR(16),
                        type VARCHAR(255) NOT NULL
                    )""");
            stmt.execute("""
                    CREATE TABLE wallets (
                        id BIGSERIAL PRIMARY KEY,
                        amount NUMERIC(12, 2) NOT NULL DEFAULT 0,
                        created_date TIMESTAMP,
                        update_date TIMESTAMP,
                        user_id BIGINT UNIQUE REFERENCES users(id)
                    )""");
            stmt.execute("""
                    CREATE TABLE transactions (
                        id BIGSERIAL PRIMARY KEY,
                        amount NUMERIC(12, 2) NOT NULL,
                        transferring_id BIGINT REFERENCES wallets(id),
                        receiving_id BIGINT REFERENCES wallets(id),
                        timestamp TIMESTAMP NOT NULL
                    )""");
            stmt.executeUpdate("INSERT INTO users (name, surname, document, email, password, password_encoding, type) " +
                    "VALUES ('Clara', 'Dias', '11122233344', 'clara@test.com', '$2a$10$abc', 'BCRYPT', 'MERCHANT')");
        }

        Flyway baselineFlyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration")
                .baselineOnMigrate(true)
                .baselineVersion("3")
                .load();

        var baselineResult = baselineFlyway.migrate();
        assertThat(baselineResult.migrationsExecuted).isZero();

        MigrationInfo[] allInfo = baselineFlyway.info().all();
        assertThat(Arrays.stream(allInfo)
                .filter(i -> i.getState() == MigrationState.BASELINE)
                .map(i -> i.getVersion().getVersion()))
                .containsExactly("3");

        // Future V4 runs incrementally from baseline 3
        Files.writeString(tempDir.resolve("V4__add_external_ref.sql"),
                "ALTER TABLE transactions ADD COLUMN external_ref VARCHAR(64);");

        Flyway nextFlyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration", "filesystem:" + tempDir.toAbsolutePath())
                .baselineOnMigrate(true)
                .baselineVersion("3")
                .load();

        var nextResult = nextFlyway.migrate();
        assertThat(nextResult.migrationsExecuted).isEqualTo(1);
        assertThat(Arrays.stream(nextFlyway.info().applied()).map(i -> i.getVersion().getVersion()))
                .containsExactly("3", "4");

        // Pre-existing row preserved
        try (Connection conn = ds.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery("SELECT count(*) FROM users WHERE email = 'clara@test.com'")) {
            assertThat(rs.next()).isTrue();
            assertThat(rs.getInt(1)).isEqualTo(1);
        }
    }

    @Test
    @DisplayName("Fails immediately when a pending migration contains invalid SQL")
    void failsWhenPendingMigrationHasInvalidSql(@TempDir Path tempDir) throws Exception {
        DataSource ds = createPostgresModeH2DataSource();
        Files.writeString(tempDir.resolve("V4__broken_migration.sql"),
                "ALTER TABLE non_existent_table ADD COLUMN broken VARCHAR(10);");

        Flyway flyway = Flyway.configure()
                .dataSource(ds)
                .locations("classpath:db/migration", "filesystem:" + tempDir.toAbsolutePath())
                .load();

        assertThatThrownBy(flyway::migrate).isInstanceOf(FlywayException.class);
    }
}
